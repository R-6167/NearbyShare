#!/usr/bin/env bash
# Install Android SDK command-line tools (no Android Studio) and project packages.
# Writes android/local.properties for Gradle.
set -euo pipefail

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
SDK_ROOT="${ANDROID_HOME:-${ANDROID_SDK_ROOT:-$HOME/Android/Sdk}}"
CMDLINE_VERSION="${CMDLINE_VERSION:-13114758}"  # Google commandlinetools build id
COMPILE_SDK="35"
BUILD_TOOLS="35.0.0"
NDK_VERSION="27.2.12479018"

echo "==> Android SDK root: $SDK_ROOT"
mkdir -p "$SDK_ROOT/cmdline-tools"

if [[ ! -x "$SDK_ROOT/cmdline-tools/latest/bin/sdkmanager" ]]; then
  OS="$(uname -s)"
  ARCH="$(uname -m)"
  case "$OS" in
    Linux)  PLATFORM="linux" ;;
    Darwin)
      if [[ "$ARCH" == "arm64" ]]; then PLATFORM="mac_arm64"; else PLATFORM="mac"; fi
      ;;
    *)
      echo "Unsupported OS: $OS (use WSL on Windows or install SDK manually)"
      exit 1
      ;;
  esac

  ZIP_NAME="commandlinetools-${PLATFORM}-${CMDLINE_VERSION}_latest.zip"
  URL="https://dl.google.com/android/repository/${ZIP_NAME}"
  TMP="$(mktemp -d)"
  echo "==> Downloading $URL"
  if command -v curl >/dev/null 2>&1; then
    curl -fsSL -o "$TMP/cmdline-tools.zip" "$URL"
  else
    wget -q -O "$TMP/cmdline-tools.zip" "$URL"
  fi
  unzip -q "$TMP/cmdline-tools.zip" -d "$TMP"
  rm -rf "$SDK_ROOT/cmdline-tools/latest"
  mkdir -p "$SDK_ROOT/cmdline-tools"
  # Zip contains a top-level cmdline-tools/ directory
  if [[ -d "$TMP/cmdline-tools" ]]; then
    mv "$TMP/cmdline-tools" "$SDK_ROOT/cmdline-tools/latest"
  else
    mv "$TMP"/* "$SDK_ROOT/cmdline-tools/latest"
  fi
  rm -rf "$TMP"
fi

export ANDROID_HOME="$SDK_ROOT"
export ANDROID_SDK_ROOT="$SDK_ROOT"
export PATH="$SDK_ROOT/cmdline-tools/latest/bin:$SDK_ROOT/platform-tools:$PATH"

SDKMANAGER="$SDK_ROOT/cmdline-tools/latest/bin/sdkmanager"
if [[ ! -x "$SDKMANAGER" ]]; then
  echo "sdkmanager not found at $SDKMANAGER"
  exit 1
fi

echo "==> Accepting licenses"
yes | "$SDKMANAGER" --sdk_root="$SDK_ROOT" --licenses >/dev/null || true

echo "==> Installing platform-tools, platforms;android-${COMPILE_SDK}, build-tools;${BUILD_TOOLS}, ndk"
"$SDKMANAGER" --sdk_root="$SDK_ROOT" \
  "platform-tools" \
  "platforms;android-${COMPILE_SDK}" \
  "build-tools;${BUILD_TOOLS}" \
  "ndk;${NDK_VERSION}"

# local.properties for Gradle
LOCAL_PROPS="$ROOT/android/local.properties"
{
  echo "## Generated by scripts/setup-android-sdk.sh – do not commit"
  echo "sdk.dir=$(echo "$SDK_ROOT" | sed 's/\\/\\\\/g')"
} > "$LOCAL_PROPS"
echo "==> Wrote $LOCAL_PROPS"

# Shell hint
cat <<EOF

Add to your shell profile (optional):

  export ANDROID_HOME="$SDK_ROOT"
  export ANDROID_SDK_ROOT="$SDK_ROOT"
  export ANDROID_NDK_HOME="$SDK_ROOT/ndk/${NDK_VERSION}"
  export PATH="\$ANDROID_HOME/cmdline-tools/latest/bin:\$ANDROID_HOME/platform-tools:\$PATH"

Next:
  ./scripts/bootstrap-gradle-wrapper.sh
  ./scripts/build-apk.sh

EOF
